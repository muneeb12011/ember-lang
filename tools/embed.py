#!/usr/bin/env python3
"""Generate src/rt_data.hpp: the C runtime and the Ember standard library, embedded as string literals so the
`embc` binary is self-contained (no install directory, nothing to find at run time).

    python3 tools/embed.py > src/rt_data.hpp
"""
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DELIM = "EMBER_RAW_7f3a"


def lit(text):
    if ")" + DELIM + '"' in text:
        sys.exit("embed.py: delimiter collision")
    return 'R"' + DELIM + "(" + text + ")" + DELIM + '"'


def main():
    out = ["// generated by tools/embed.py - do not edit", "#pragma once", ""]
    out.append("struct EmbeddedFile { const char* name; const char* text; };")
    with open(os.path.join(ROOT, "rt", "ember_rt.c")) as fh:
        out.append("static const char* const kRuntimeSource = " + lit(fh.read()) + ";")
    with open(os.path.join(ROOT, "rt", "ember_rt_wasm.c")) as fh:
        out.append("static const char* const kWasmRuntimeSource = " + lit(fh.read()) + ";")
    with open(os.path.join(ROOT, "rt", "ember_wasm.js")) as fh:
        out.append("static const char* const kWasmLoader = " + lit(fh.read()) + ";")
    out.append("static const EmbeddedFile kStdlib[] = {")
    for path in sorted(glob.glob(os.path.join(ROOT, "std", "**", "*.em"), recursive=True)):
        name = os.path.relpath(path, os.path.join(ROOT, "std")).replace(os.sep, "/")
        with open(path) as fh:
            out.append('    {"std/%s", %s},' % (name, lit(fh.read())))
    out.append("    {nullptr, nullptr}};")
    sys.stdout.write("\n".join(out) + "\n")


main()
